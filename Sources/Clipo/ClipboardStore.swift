import AppKit
import CryptoKit

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, image, file }

    var id = UUID()
    var kind: Kind
    /// Text content, or file paths separated by newlines for `.file`.
    var text: String
    var imageName: String?
    var hash: String
    var date = Date()
    var pinned = false
    var appBundleID: String?
    /// Rich representations (RTF, HTML, …) saved next to the plain text: pasteboard type → file name.
    var formats: [String: String]?

    var filePaths: [String] { kind == .file ? text.components(separatedBy: "\n") : [] }
    var hasFormatting: Bool { formats?.isEmpty == false }
}

/// Watches the system pasteboard and keeps a persistent history of copied items.
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    var limit: Int { Preferences.shared.historyLimit }

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private let imagesFolder: URL
    private let formatsFolder: URL
    private let historyFile: URL
    private let imageCache = NSCache<NSString, NSImage>()
    private var iconCache: [String: NSImage] = [:]

    /// Markers used by password managers and other apps for content that should not be recorded.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    init() {
        lastChangeCount = pasteboard.changeCount
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        let folder = support.appendingPathComponent("Clipo", isDirectory: true)
        imagesFolder = folder.appendingPathComponent("images", isDirectory: true)
        formatsFolder = folder.appendingPathComponent("formats", isDirectory: true)
        historyFile = folder.appendingPathComponent("history.json")
        try? FileManager.default.createDirectory(at: imagesFolder, withIntermediateDirectories: true)
        load()
    }

    func start() {
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.checkPasteboard() }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    // MARK: - Capture

    private func checkPasteboard() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = pasteboard.types ?? []
        guard !types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) else { return }
        let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path).joined(separator: "\n")
            insert(ClipItem(kind: .file, text: paths, hash: Self.hash(Data(paths.utf8)), appBundleID: app))
        } else if let string = pasteboard.string(forType: .string),
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            var item = ClipItem(kind: .text, text: string, hash: Self.hash(Data(string.utf8)), appBundleID: app)
            item.formats = saveFormats(for: item.id)
            insert(item)
        } else if let png = Self.pngData(from: pasteboard) {
            let hash = Self.hash(png)
            let name = hash + ".png"
            let url = imagesFolder.appendingPathComponent(name)
            if !FileManager.default.fileExists(atPath: url.path) { try? png.write(to: url) }
            insert(ClipItem(kind: .image, text: "", imageName: name, hash: hash, appBundleID: app))
        }
    }

    /// Saves every representation of the copied item except plain text, so formatting survives.
    private func saveFormats(for id: UUID) -> [String: String]? {
        guard let source = pasteboard.pasteboardItems?.first else { return nil }
        let types = source.types.filter { $0 != .string }
        guard !types.isEmpty else { return nil }

        let folder = formatsFolder.appendingPathComponent(id.uuidString, isDirectory: true)
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        var saved: [String: String] = [:]
        var totalSize = 0
        for (index, type) in types.enumerated() {
            guard let data = source.data(forType: type), totalSize + data.count <= 20_000_000 else { continue }
            let name = "\(index)"
            guard (try? data.write(to: folder.appendingPathComponent(name))) != nil else { continue }
            saved[type.rawValue] = name
            totalSize += data.count
        }
        if saved.isEmpty { try? FileManager.default.removeItem(at: folder) }
        return saved.isEmpty ? nil : saved
    }

    private func insert(_ new: ClipItem) {
        var item = new
        if let index = items.firstIndex(where: { $0.hash == new.hash }) {
            item.pinned = items[index].pinned
            let old = items.remove(at: index)
            deleteFiles(old)
        }
        items.insert(item, at: 0)
        trim()
        save()
    }

    func trim() {
        var unpinned = 0
        var removed: [ClipItem] = []
        items.removeAll { item in
            guard !item.pinned else { return false }
            unpinned += 1
            guard unpinned > limit else { return false }
            removed.append(item)
            return true
        }
        removed.forEach(deleteFiles)
        if !removed.isEmpty { save() }
    }

    // MARK: - Actions

    /// Puts the item back on the system pasteboard and moves it to the top of the history.
    /// `plainText` drops formatting for text items.
    func copy(_ item: ClipItem, plainText: Bool = false) {
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            if !plainText, let formats = item.formats {
                let restored = NSPasteboardItem()
                restored.setString(item.text, forType: .string)
                let folder = formatsFolder.appendingPathComponent(item.id.uuidString, isDirectory: true)
                for (type, name) in formats {
                    if let data = try? Data(contentsOf: folder.appendingPathComponent(name)) {
                        restored.setData(data, forType: NSPasteboard.PasteboardType(type))
                    }
                }
                pasteboard.writeObjects([restored])
            } else {
                pasteboard.setString(item.text, forType: .string)
            }
        case .file:
            pasteboard.writeObjects(item.filePaths.map { URL(fileURLWithPath: $0) as NSURL })
        case .image:
            if let name = item.imageName,
               let data = try? Data(contentsOf: imagesFolder.appendingPathComponent(name)) {
                pasteboard.setData(data, forType: .png)
                if let tiff = NSImage(data: data)?.tiffRepresentation {
                    pasteboard.setData(tiff, forType: .tiff)
                }
            }
        }
        lastChangeCount = pasteboard.changeCount

        if !item.pinned, let index = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        trim()
        save()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        deleteFiles(item)
        save()
    }

    /// Like Windows: "Clear all" keeps pinned items.
    func clearUnpinned() {
        let removed = items.filter { !$0.pinned }
        items.removeAll { !$0.pinned }
        removed.forEach(deleteFiles)
        save()
    }

    var hasUnpinned: Bool { items.contains { !$0.pinned } }

    /// Pinned items first, then the rest, newest first.
    func visible(matching query: String) -> [ClipItem] {
        let query = query.trimmingCharacters(in: .whitespaces)
        let filtered = query.isEmpty
            ? items
            : items.filter { $0.kind != .image && $0.text.localizedCaseInsensitiveContains(query) }
        return filtered.filter(\.pinned) + filtered.filter { !$0.pinned }
    }

    // MARK: - Images & icons

    func image(for item: ClipItem) -> NSImage? {
        guard let name = item.imageName else { return nil }
        if let cached = imageCache.object(forKey: name as NSString) { return cached }
        guard let image = NSImage(contentsOf: imagesFolder.appendingPathComponent(name)) else { return nil }
        imageCache.setObject(image, forKey: name as NSString)
        return image
    }

    func appIcon(for bundleID: String?) -> NSImage? {
        guard let bundleID else { return nil }
        if let cached = iconCache[bundleID] { return cached }
        guard let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID) else { return nil }
        let icon = NSWorkspace.shared.icon(forFile: url.path)
        iconCache[bundleID] = icon
        return icon
    }

    func appName(for bundleID: String?) -> String? {
        guard let bundleID, let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID) else { return nil }
        return FileManager.default.displayName(atPath: url.path).replacingOccurrences(of: ".app", with: "")
    }

    /// Removes an item's saved formats and its image, unless another item shares that image.
    private func deleteFiles(_ item: ClipItem) {
        if item.formats != nil {
            try? FileManager.default.removeItem(at: formatsFolder.appendingPathComponent(item.id.uuidString))
        }
        guard let name = item.imageName, !items.contains(where: { $0.imageName == name }) else { return }
        try? FileManager.default.removeItem(at: imagesFolder.appendingPathComponent(name))
        imageCache.removeObject(forKey: name as NSString)
    }

    // MARK: - Persistence

    private func load() {
        guard let data = try? Data(contentsOf: historyFile),
              let saved = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = saved
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: historyFile, options: .atomic)
    }

    // MARK: - Helpers

    private static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    private static func pngData(from pasteboard: NSPasteboard) -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}
